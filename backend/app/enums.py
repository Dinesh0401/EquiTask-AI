    OPTIMAL_PROPOSALS = "OPTIMAL_PROPOSALS"
    FEASIBLE_PROPOSALS = "FEASIBLE_PROPOSALS"
    NO_FEASIBLE_PROPOSAL = "NO_FEASIBLE_PROPOSAL"
